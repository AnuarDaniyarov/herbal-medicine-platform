CREATE TABLE plants (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scientific_name VARCHAR(250) NOT NULL UNIQUE,
    display_name VARCHAR(250) NOT NULL,
    family VARCHAR(250),
    description TEXT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE compounds (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(250) NOT NULL,
    canonical_smiles VARCHAR(2000) NOT NULL,
    inchi_key VARCHAR(100) UNIQUE,
    external_id VARCHAR(200) UNIQUE,
    molecular_formula VARCHAR(100),
    structure_status VARCHAR(30) NOT NULL DEFAULT 'UNVERIFIED',
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX ix_compounds_name ON compounds (name);
CREATE INDEX ix_compounds_smiles ON compounds (canonical_smiles);

CREATE TABLE sources (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(1000) NOT NULL,
    authors VARCHAR(1000),
    publication_year INTEGER,
    doi VARCHAR(300) UNIQUE,
    url VARCHAR(2000),
    source_type VARCHAR(50) NOT NULL,
    accessed_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_sources_publication_year CHECK (publication_year IS NULL OR publication_year BETWEEN 1000 AND 9999)
);

CREATE TABLE plant_compound_relationships (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plant_id BIGINT NOT NULL REFERENCES plants (id) ON DELETE CASCADE,
    compound_id BIGINT NOT NULL REFERENCES compounds (id) ON DELETE CASCADE,
    plant_part VARCHAR(250),
    sample_or_batch VARCHAR(250),
    source_id BIGINT REFERENCES sources (id) ON DELETE SET NULL,
    notes TEXT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX ix_plant_compound_relationships_plant ON plant_compound_relationships (plant_id);
CREATE INDEX ix_plant_compound_relationships_compound ON plant_compound_relationships (compound_id);

CREATE TABLE assays (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    activity_code VARCHAR(100) NOT NULL UNIQUE,
    name VARCHAR(250) NOT NULL,
    target_name VARCHAR(250),
    assay_type VARCHAR(100),
    description TEXT,
    standard_unit VARCHAR(50),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

