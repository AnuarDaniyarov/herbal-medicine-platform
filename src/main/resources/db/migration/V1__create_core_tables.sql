CREATE TABLE activity_measurements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    compound_id BIGINT NOT NULL REFERENCES compounds (id) ON DELETE CASCADE,
    assay_id BIGINT NOT NULL REFERENCES assays (id),
    source_id BIGINT NOT NULL REFERENCES sources (id),
    measurement_value DECIMAL(18, 8) NOT NULL,
    unit VARCHAR(50) NOT NULL,
    relation VARCHAR(10) NOT NULL DEFAULT '=',
    experimental_conditions TEXT,
    quality_status VARCHAR(30) NOT NULL DEFAULT 'UNVERIFIED',
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_activity_measurements_relation CHECK (relation IN ('=', '<', '<=', '>', '>='))
);

CREATE INDEX ix_activity_measurements_compound ON activity_measurements (compound_id);
CREATE INDEX ix_activity_measurements_assay ON activity_measurements (assay_id);

CREATE TABLE model_versions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(200) NOT NULL,
    version VARCHAR(100) NOT NULL,
    activity_code VARCHAR(100) NOT NULL,
    execution_type VARCHAR(30) NOT NULL,
    training_data_description TEXT,
    metrics_json TEXT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    is_active BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT uq_model_versions_name_version UNIQUE (name, version)
);

CREATE TABLE predictions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    compound_id BIGINT REFERENCES compounds (id) ON DELETE SET NULL,
    input_smiles VARCHAR(2000) NOT NULL,
    activity_code VARCHAR(100) NOT NULL,
    predicted_label VARCHAR(100),
    predicted_value DECIMAL(18, 8),
    probability DECIMAL(8, 7),
    confidence_level VARCHAR(30),
    model_version_id BIGINT NOT NULL REFERENCES model_versions (id),
    warning VARCHAR(2000) NOT NULL,
    status VARCHAR(30) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_predictions_probability CHECK (probability IS NULL OR probability BETWEEN 0 AND 1)
);

CREATE INDEX ix_predictions_compound ON predictions (compound_id);
CREATE INDEX ix_predictions_created_at ON predictions (created_at);

